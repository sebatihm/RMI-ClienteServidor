    private void jTable2MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable2MouseClicked
        int row = jTable2.getSelectedRow();
        try {
            selectedAppointment = appointmentService.getAppointment((Integer)tablemodel.getValueAt(row, 0));
            String fechaFormateada = new SimpleDateFormat("yyyy-MM-dd").format(selectedAppointment.getDate());
            jTextField2.setText(fechaFormateada);
            jTextField1.setText(selectedAppointment.getHour().toString());
            jTextField3.setText(selectedAppointment.getSubject());
            
            int docint = getSelectedDoctor(doctorModels, selectedAppointment.getDoctor().getId());
            jList1.setSelectedIndex(docint);
                    

            int patint =getSelectedPatient(patientsModels, selectedAppointment.getPatient().getId());
            jList2.setSelectedIndex(patint);
            
            jButton1.setEnabled(false);
            jButton2.setEnabled(true);
            jButton3.setEnabled(true);
            jButton4.setEnabled(true);
        } catch (RemoteException ex) {
            Logger.getLogger(AppointmentPanel.class.getName()).log(Level.SEVERE, null, ex);
        }
         
    }//GEN-LAST:event_jTable2MouseClicked

