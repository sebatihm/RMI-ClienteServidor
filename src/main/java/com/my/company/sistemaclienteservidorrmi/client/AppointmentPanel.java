    private int getSelectedPatient(List<Patient> patientsModels, int id) {
        int i = 0;
        for(Patient pat : patientsModels){
            if(pat.getId() == id){
                return i;
            }
            i++;
        }
        
        return -1;
    }
    private int getSelectedDoctor(List<Doctor> doctorModels, int id){
        int i = 0;
        for(Doctor doc : doctorModels){
            if(doc.getId() == id){
                return i;
            }
            i++;
        }
        
        return -1;
    }
