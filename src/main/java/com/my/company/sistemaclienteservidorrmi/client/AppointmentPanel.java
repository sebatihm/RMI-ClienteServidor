    public void loadAppointments( DefaultTableModel tableModel){
        try {
            tableModel.setRowCount(0);
            List<Appointment> appointments = appointmentService.getAllAppointments();
            for (Appointment appointment : appointments) {
                appointment.getDoctor();
                appointment.getPatient();
                tableModel.addRow(new Object[] {
                        appointment.getId(),
                        appointment.getDate(),
                        appointment.getHour(),
                        appointment.getSubject(),
                        appointment.getDoctor().getName(),
                        appointment.getPatient().getName()
                });
            }
            
            DefaultListModel<String> doctors = new DefaultListModel<>();
            doctorModels = doctorService.getAllDoctors();
            for(Doctor doctor: doctorModels){
                doctors.addElement(doctor.getName()); 
            }
            jList1.setModel(doctors);
            
            DefaultListModel<String> patients = new DefaultListModel<>();
            patientsModels = patientService.getAllPatients();
            
            for(Patient patient: patientsModels){
                patients.addElement(patient.getName());
            }
            jList2.setModel(patients);
            
            
            
        } catch (RemoteException e) {
            JOptionPane.showMessageDialog(this, "Error cargando médicos: " + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
        
        
        
        
        
    }

